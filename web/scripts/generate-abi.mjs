// Regenerates src/lib/contracts/*.ts from the Foundry build. Run after changing contracts/.
import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const contractsDir = fileURLToPath(new URL("../../contracts", import.meta.url))
const outFile = fileURLToPath(
  new URL("../src/lib/contracts/vindicate-delegate.ts", import.meta.url),
)

const abi = execFileSync("forge", ["inspect", "VindicateDelegate", "abi", "--json"], {
  cwd: contractsDir,
  encoding: "utf8",
}).trim()

writeFileSync(
  outFile,
  `// Generated by scripts/generate-abi.mjs from contracts/. Do not edit by hand.\nexport const vindicateDelegateAbi = ${abi} as const\n`,
)
console.log(`wrote ${outFile}`)
